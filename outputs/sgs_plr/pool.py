"""Stack reset pool with the "let go" shortcut removed from the evaluation split.

Starts are generated by sgs_plr/resets.py (Reaching / Grasp / Near-Goal,
cube A picked up with real OSC gripper closes, no finger or cube teleports).
Every start is then tested with two fixed policies that hold the arm still, one
opening the gripper and one keeping it closed. If either stacks within the start's
time limit, the start is tagged `trivial`.

- eval split: trivial starts are rejected and resampled, so a success there needs
  more than letting go. `home` (the full task) is included.
- train split: trivial starts are kept and tagged (they are a legitimate easy
  stepping stone, like the paper's Near-Goal family); the fraction is recorded.

    PYTHONPATH=. ../robosuite/.venv/bin/python -m sgs_plr.pool --out stack_omnireset_pools/f2
"""
import os
for _key in ('OMP_NUM_THREADS', 'OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS',
             'VECLIB_MAXIMUM_THREADS', 'NUMEXPR_NUM_THREADS'):
    os.environ.setdefault(_key, '1')
import argparse
import json
import time
from multiprocessing import get_context
from pathlib import Path

import numpy as np
from robosuite.utils.control_utils import orientation_error

from uniform.stack_intermediate import eef_pose
from sgs.stack_omnireset import LIMITS, TRAIN_FAMILIES, Reject
from sgs.stack_task_ladder import Tracker, new_env, restore, snapshot
from sgs_plr.resets import make_config

HOLD_STEPS = 5


def still_succeeds(env, ori, limit, grip=-1., hold_steps=HOLD_STEPS):
    """From the current state, hold the arm still with gripper command `grip` for `limit` steps."""
    tracker = Tracker()
    tracker.required_steps = hold_steps
    tracker.reset()
    for _ in range(limit):
        rot = np.clip(orientation_error(ori, eef_pose(env)[1]), -.1, .1) / .5
        env.step(np.r_[0, 0, 0, rot, grip])
        if tracker.update(env)['stable_now']:
            return True
    return False


def _build(args):
    family, split, n, seed, tag_train = args
    env = new_env()
    rng = np.random.default_rng(seed)
    out, rejects, trivial_rejects, trivial_kept = [], 0, 0, 0
    while len(out) < n:
        try:
            info = make_config(env, family, rng)
        except Reject:
            rejects += 1
            if rejects > n * 80:
                raise RuntimeError(f'{family}: too many rejects ({rejects}) for {n} starts')
            continue
        env.timestep = 0
        snap = snapshot(env)
        ori = eef_pose(env)[1]
        trivial = False
        if family != 'home' and (split == 'eval' or tag_train):
            trivial = still_succeeds(env, ori, LIMITS[family], -1.)          # let go
            if not trivial:
                restore(env, snap)
                trivial = still_succeeds(env, ori, LIMITS[family], 1.)       # stay closed
        if trivial and split == 'eval':
            trivial_rejects += 1
            continue
        trivial_kept += trivial
        out.append((dict(info, trivial=bool(trivial)), snap))
    env.close()
    return dict(family=family, split=split, items=out, rejects=rejects,
                trivial_rejects=trivial_rejects, trivial_kept=trivial_kept)


def build(train_per_family, eval_per_family, seed, out, chunk=128, procs=7, tag_train=True):
    jobs = []
    for i, f in enumerate(TRAIN_FAMILIES):    # train starts in chunks so large pools use all procs
        for c, lo in enumerate(range(0, train_per_family, chunk)):
            jobs.append((f, 'train', min(chunk, train_per_family - lo),
                         seed * 100 + i if c == 0 else seed * 100000 + i * 1000 + c, tag_train))
    jobs += [(f, 'eval', eval_per_family, seed * 100 + 50 + i, True)
             for i, f in enumerate(('home',) + TRAIN_FAMILIES)]
    t0 = time.time()
    with get_context('spawn').Pool(min(len(jobs), procs)) as pool:
        results = pool.map(_build, jobs)
    merged = {}                               # merge chunks of the same (split, family)
    for r in results:
        key = (r['split'], r['family'])
        if key not in merged:
            merged[key] = dict(r, items=list(r['items']))
        else:
            m = merged[key]
            m['items'] += r['items']
            for k in ('rejects', 'trivial_rejects', 'trivial_kept'):
                m[k] += r[k]
    results = list(merged.values())
    meta, states, grips, stats = [], [], [], []
    for r in results:
        stats.append({k: v for k, v in r.items() if k != 'items'} | dict(kept=len(r['items'])))
        infos = [i for i, _ in r['items']]
        held = sum(i.get('cube_held', False) for i in infos)
        air = sum(i.get('airborne', False) for i in infos)
        stats[-1].update(cube_held=held, airborne=air,
                         cells=sorted({i['cell'] for i in infos if 'cell' in i}),
                         cells_fine=sorted({i['cell_fine'] for i in infos if 'cell_fine' in i}))
        print(f'{r["split"]:5} {r["family"]:10} kept {len(r["items"]):3}  invalid {r["rejects"]:4}  '
              f'trivial rejected {r["trivial_rejects"]:4}  trivial kept {r["trivial_kept"]:3}  '
              f'cube held {held:3}  airborne {air:3}', flush=True)
        for info, snap in r['items']:
            meta.append(dict(id=len(meta), split=r['split'], label=r['family'],
                             limit=LIMITS[r['family']], steps_before_stack=LIMITS[r['family']], **info))
            states.append(snap['state'])
            grips.append(snap['grip'])
    out = Path(out)
    out.mkdir(parents=True, exist_ok=False)
    np.savez_compressed(out / 'pool.npz', states=np.stack(states), grips=np.stack(grips))
    (out / 'pool.json').write_text(json.dumps(dict(
        kind='stack-omnireset-filtered', seed=seed, train_trivial_tagged=tag_train, hold_steps=HOLD_STEPS, grasp='osc-close',
        eval_filter='reject starts solved by holding still with the gripper open or closed', generation_stats=stats,
        labels=['home', *TRAIN_FAMILIES], train_families=list(TRAIN_FAMILIES),
        limits=LIMITS, configurations=meta), indent=1) + '\n')
    print(f'pool: {out} ({len(meta)} starts, {time.time() - t0:.0f}s)', flush=True)
    return out


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--train-per-family', type=int, default=32)
    p.add_argument('--eval-per-family', type=int, default=64)
    p.add_argument('--seed', type=int, default=11)
    p.add_argument('--out', type=Path, required=True)
    p.add_argument('--chunk', type=int, default=128, help='training starts per worker job')
    p.add_argument('--procs', type=int, default=7)
    p.add_argument('--no-tag-train', action='store_true',
                   help='skip the trivial-start test on training starts (faster for large pools)')
    a = p.parse_args()
    build(a.train_per_family, a.eval_per_family, a.seed, a.out, a.chunk, a.procs, not a.no_tag_train)


if __name__ == '__main__':
    main()
